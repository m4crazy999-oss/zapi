  /// Aplica modificador de tom de pele (Fitzpatrick) a emojis compatíveis,
  /// preservando sequências com ZWJ (ex.: 🧑‍💻, 🙋‍♀️).
  static String applySkinTone(String emoji, String? modifier,
      {bool supportsSkinTone = true}) {
    if (!supportsSkinTone || modifier == null || modifier.isEmpty) {
      return emoji;
    }

    const zwj = '\u200D';
    const fe0f = '\uFE0F';

    // Se for sequência ZWJ (ex.: 🙋‍♀️ ou 🧑‍💻), aplica no primeiro segmento
    final zwjIdx = emoji.indexOf(zwj);
    if (zwjIdx > 0) {
      final head = emoji.substring(0, zwjIdx).replaceAll(fe0f, '');
      final tail = emoji.substring(zwjIdx);
      return '$head$modifier$tail';
    }

    // Remove U+FE0F final se existir (ex.: ✌️ -> ✌ + tone, ☝️ -> ☝ + tone)
    final cleaned = emoji.replaceAll(fe0f, '');
    return '$cleaned$modifier';
  }

